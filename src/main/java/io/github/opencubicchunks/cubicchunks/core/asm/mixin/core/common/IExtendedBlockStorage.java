package io.github.opencubicchunks.cubicchunks.core.asm.mixin.core.common;

import net.minecraft.world.chunk.storage.ExtendedBlockStorage;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.gen.Accessor;

/** A storage's counts of blocks and of randomly ticking blocks, for a cube built a run of blocks at a time. */
@Mixin(ExtendedBlockStorage.class)
public interface IExtendedBlockStorage {

    @Accessor int getBlockRefCount();

    @Accessor void setBlockRefCount(int count);

    @Accessor int getTickRefCount();

    @Accessor void setTickRefCount(int count);
}
